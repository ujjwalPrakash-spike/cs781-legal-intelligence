#!/usr/bin/env python3
"""
07_phase6_mbr_medoid_consensus.py
-----------------------------------
CS781 Capstone - Viva Voce Demonstration Script
Phase 6: Minimum Bayes Risk (MBR) Medoid Decoding for Summarization Ensembles

Why this matters for Viva:
1. Multi-model ensembling in generative tasks cannot use standard majority voting or
   simple probability averaging because candidate outputs are free-form text sequences.
2. Minimum Bayes Risk (MBR) decoding treats candidate summaries from diverse models
   as both hypotheses and pseudo-references.
3. The selected summary is the "medoid" - the hypothesis that maximizes expected utility
   (pairwise ROUGE-L similarity) against all other ensemble candidates:
       y* = argmax_{y_i} sum_{j=1}^M ROUGE-L(y_i, y_j)
4. This mathematically filters out isolated hallucinations and degenerative repetitions.
"""

def lcs_length(tokens_a, tokens_b):
    """
    Computes the Length of Longest Common Subsequence (LCS) between two token lists.
    Standard dynamic programming formulation used in ROUGE-L.
    """
    m, n = len(tokens_a), len(tokens_b)
    # Use 1D rolling array for O(min(m, n)) space
    dp = [0] * (n + 1)
    
    for i in range(1, m + 1):
        prev = 0
        for j in range(1, n + 1):
            temp = dp[j]
            if tokens_a[i - 1] == tokens_b[j - 1]:
                dp[j] = prev + 1
            else:
                dp[j] = max(dp[j], dp[j - 1])
            prev = temp
    return dp[n]


def compute_rouge_l(summary_a, summary_b):
    """
    Computes pairwise ROUGE-L F1 score between two string texts.
    """
    tokens_a = summary_a.lower().split()
    tokens_b = summary_b.lower().split()
    
    if not tokens_a or not tokens_b:
        return 0.0
        
    lcs = lcs_length(tokens_a, tokens_b)
    prec = lcs / len(tokens_a)
    rec = lcs / len(tokens_b)
    
    if (prec + rec) == 0:
        return 0.0
    return (2 * prec * rec) / (prec + rec)


def mbr_medoid_selection(candidates):
    """
    Selects the medoid candidate that maximizes cumulative ROUGE-L consensus.
    candidates: list of (model_name, summary_text)
    """
    num_candidates = len(candidates)
    score_matrix = [[0.0] * num_candidates for _ in range(num_candidates)]
    
    for i in range(num_candidates):
        for j in range(i, num_candidates):
            if i == j:
                score = 1.0
            else:
                score = compute_rouge_l(candidates[i][1], candidates[j][1])
            score_matrix[i][j] = score
            score_matrix[j][i] = score
            
    # Compute row sums (cumulative consensus score)
    consensus_scores = [sum(score_matrix[i]) for i in range(num_candidates)]
    best_idx = max(range(num_candidates), key=lambda i: consensus_scores[i])
    
    return best_idx, score_matrix, consensus_scores


def main():
    print("=== Phase 6: MBR Medoid Consensus Decoding ===")
    
    # 5 Candidate summaries generated by diverse checkpoints for a legal case
    candidates = [
        ("Model_1_LegalLED", 
         "The appellant filed for bail under Section 439 CrPC. The High Court denied bail citing prima facie evidence of forgery and criminal conspiracy under IPC 420 and 467."),
        
        ("Model_2_BART_Legal", 
         "The Supreme Court heard an appeal challenging the denial of bail by the High Court under Section 439 CrPC. Considering the gravity of economic offenses under IPC 420 and 467, the bail petition is dismissed."),
        
        ("Model_3_InLegal_T5", 
         "The accused sought regular bail under Section 439 of CrPC. The court observed strong prima facie evidence under Section 420 and Section 467 of IPC. Bail petition was rejected."),
        
        ("Model_4_Hallucinated", 
         "The defendant was sentenced to ten years imprisonment for maritime piracy under international admiralty law and narcotics possession."), # Severe hallucination
        
        ("Model_5_Repetitive", 
         "Bail petition under Section 439 CrPC denied denied denied under Section 420 467 IPC.") # Degenerative repetition
    ]
    
    print(f"Total Candidate Summaries in Ensemble: {len(candidates)}")
    for i, (name, text) in enumerate(candidates):
        print(f"  [{i}] {name}: \"{text[:75]}...\"")
        
    best_idx, matrix, scores = mbr_medoid_selection(candidates)
    
    print("\nPairwise ROUGE-L Affinity Matrix:")
    header = "       " + "".join([f"M{k:<7}" for k in range(len(candidates))]) + "Consensus Sum"
    print(header)
    print("-" * len(header))
    for i in range(len(candidates)):
        row_str = f"M{i:<6}" + "".join([f"{matrix[i][j]:.4f} " for j in range(len(candidates))])
        row_str += f" -> {scores[i]:.4f}"
        print(row_str)
        
    selected_model, selected_text = candidates[best_idx]
    print(f"\nOptimal Ensemble Medoid Selected: [{best_idx}] {selected_model}")
    print(f"Highest Consensus Score: {scores[best_idx]:.4f}")
    print(f"Selected Summary Text:\n\"{selected_text}\"")
    print("\nNotice how M3/M1/M2 agree on the legal facts, while M4 (hallucination) scored only "
          f"{scores[3]:.4f} and M5 (repetition) scored only {scores[4]:.4f}, rejecting both cleanly.")
    print("Execution completed successfully.")

if __name__ == "__main__":
    main()
